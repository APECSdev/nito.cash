/* apps/web/vitest.config.js
 *
 * Vitest config (Phase C of the Vue 3 migration). Replaces Jest
 * (`jest.config.js` / `vue-cli-service test:unit`), which was tied to
 * `@vue/test-utils@1` (Vue 2). Shares the Vite pipeline (plugin-vue, `@`
 * alias) so SFCs compile exactly as they do for the app build.
 */
import { fileURLToPath, URL } from 'node:url'

import { defineConfig } from 'vitest/config'
import vue from '@vitejs/plugin-vue'

export default defineConfig({
    plugins: [
        /* Vue 3 SFC support for tests. */
        vue(),
    ],

    resolve: {
        alias: [
            /* Mirror the app's `@ -> src` alias. */
            { find: '@', replacement: fileURLToPath(new URL('./src', import.meta.url)) },

            /* Components import { mapGetters, mapActions, mapState } from
               'vuex'; alias the bare specifier to the Pinia-backed shim. */
            { find: /^vuex$/, replacement: fileURLToPath(new URL('./src/store/vuex-shim.js', import.meta.url)) },
        ],
        /* The codebase imports SFCs extensionless in places. */
        extensions: ['.mjs', '.js', '.mts', '.ts', '.jsx', '.tsx', '.json', '.vue'],
    },

    test: {
        /* Browser-like environment. */
        environment: 'jsdom',

        /* Jest-style globals (describe/it/expect) without imports. */
        globals: true,

        /* Test file locations. */
        include: ['tests/unit/**/*.spec.js'],

        /* Shared setup (jsdom has no camera stack — see the file). */
        setupFiles: ['./tests/unit/setup.js'],

        /* Timeouts: several specs mount whole views and derive HD keys (real
           scrypt/bip32 work) — 5s is tight when 41 files share the CPUs. */
        testTimeout: 20000,
        hookTimeout: 20000,

        /* Coverage (lcov feeds Codecov; mirrors the old Jest report path).
         *
         * SCOPE: the whole shipped source tree — JavaScript AND Vue SFCs.
         * It previously measured Vue files only, so every lib/ and
         * store/ module (crypto, provider, getters, actions) was INVISIBLE
         * to the report and Codecov showed a meaningless number.
         *
         * Excluded (not unit-testable / generated):
         *   - compiled-icons: GENERATED by generate-icons (never hand-edited)
         *   - plugins:        Bugsnag bootstrap (side-effect only)
         *   - main.js:        application entry point (wiring only)
         *   - verifier-role2: node-only acceptance generator (scripts/pool-accept.mjs;
         *                     it imports the vendored bn-native-sound worktree and the
         *                     BCH-2026 VM, neither of which the browser app uses) */
        coverage: {
            provider: 'v8',
            reporter: ['lcov', 'text-summary', 'json-summary'],
            reportsDirectory: './coverage',
            include: ['src/**/*.{js,vue}'],
            exclude: [
                '**/node_modules/**',
                'src/compiled-icons/**',
                'src/plugins/**',
                'src/main.js',
                'src/lib/pool/verifier-role2.js',
                'tests/unit/**',
            ],
            /* Ratchet. The TARGET is 90% (mirrored in codecov.yml, which
               applies a 1% tolerance). The local hard floor is 89% because a
               few async view/component branches are timing-dependent and
               measured coverage moves ~±0.3% between runs — a 90% hard gate
               would fail CI at random. Measured: 89.8–90.2% lines. */
            thresholds: {
                lines: 89,
                statements: 89,
            },
        },
    },
})
